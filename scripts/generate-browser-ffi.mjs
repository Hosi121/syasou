import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// Each browser operation has one typed MoonBit declaration and one JS body.
// The JS backend inlines it; Wasm imports the identical browser operation.
export function generateBrowserFFI() {
  const imports = {}
  for (const directory of readdirSync('moonbit', { withFileTypes: true }).filter(e => e.isDirectory())) {
    const folder = join('moonbit', directory.name)
    const declarations = []
    const conversions = []
    const packageText = readFileSync(join(folder, 'moon.pkg'), 'utf8')
    // Bootstrap tools execute as JS; they are not imports of the Wasm app.
    if (/supported_targets\s*=\s*"js"/.test(packageText)) continue
    const alias = packageText.includes('@js_core') ? '@js_core' : '@js'
    for (const name of readdirSync(folder).filter(n => n.endsWith('.mbt') && !n.includes('generated') && !n.endsWith('test.mbt'))) {
      const file = join(folder, name)
      let source = readFileSync(file, 'utf8')
      if (directory.name !== 'interop') {
        for (const match of source.matchAll(/#external\s+(pub |priv )?type (\w+)(?!\w|\[)/g)) {
          if (match[1] !== 'pub ') continue
          const visibility = 'pub '
          conversions.push(`${visibility}impl ${alias}.ToJs for ${match[2]} with fn to_js(self) -> ${alias}.Any = "%identity"\n${visibility}impl ${alias}.FromJs for ${match[2]} with fn from_js(value : ${alias}.Any) -> ${match[2]} = "%identity"\n${visibility}impl ${alias}.Same for ${match[2]} with fn same(a,b) { ${alias}.same_host(${alias}.any(a), ${alias}.any(b)) }`)
        }
      }
      source = source.replace(/(?:#cfg\(target="js"\)\s*)?((?:pub )?extern "js" fn ([\w:]+)\s*\([\s\S]*?\)\s*(?:->\s*[\s\S]*?)?=)\s*(#\|[^\n]*(?:\n[ \t]*#\|[^\n]*)*|"[^"\n]+"(?:[ \t]+"[^"\n]+")?)/g, (full, signature, name, implementation) => {
        const key = `${directory.name}_${name.replaceAll('::', '_')}`
        let body = implementation.startsWith('#|') ? implementation.split('\n').map(line => line.replace(/^\s*#\| ?/, '')).join('\n') : [...implementation.matchAll(/"([^"]+)"/g)].map(m => m[1]).join('.')
        // Wasm's Bool ABI is i32. Browser dictionaries and trace tests
        // require actual JS booleans, including APIs that accept generic values.
        const parameters = []
        let depth = 0, start = signature.indexOf('(') + 1
        for (let i = start; i < signature.length; i++) {
          const c = signature[i]
          if (c === '(' || c === '[') depth++
          if (c === ')' && depth === 0) { parameters.push(signature.slice(start, i)); break }
          if (c === ')' || c === ']') depth--
          if (c === ',' && depth === 0) { parameters.push(signature.slice(start, i)); start = i + 1 }
        }
        const booleans = parameters.flatMap((p, i) => /:\s*Bool\s*$/.test(p) ? [i] : [])
        if (booleans.length) body = `(...args) => {${booleans.map(i => `args[${i}]=Boolean(args[${i}]);`).join('')}return (${body})(...args)}`
        if (imports[key]) throw new Error(`Duplicate FFI ${key}`)
        imports[key] = body
        declarations.push(signature.replace('extern "js"', 'extern "wasm"') + ` "syasou" "${key}"`)
        return `#cfg(target="js")\n${signature}\n  ${implementation}`
      })
      writeFileSync(file, source)
    }
    if (declarations.length) writeFileSync(join(folder, 'ffi_wasm.generated.mbt'), '// Generated by scripts/generate-browser-ffi.mjs.\n' + declarations.map(d => `///|\n#cfg(target="wasm-gc")\n${d}`).join('\n\n') + '\n')
    if (conversions.length) writeFileSync(join(folder, 'ffi_types.generated.mbt'), '// Typed conversions between opaque browser references.\n' + conversions.map(d => '///|\n' + d).join('\n\n') + '\n')
  }
  return imports
}
