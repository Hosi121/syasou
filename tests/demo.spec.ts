test('a keepsake awaiting storage survives reload and replay keeps the same edited ticket', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '窓辺へ', exact: true }).click()
  await receiveTicket(page)
  await page.getByRole('textbox', { name: '切符に残す作業' }).fill('わたしの最初の切符')
  const received = await readTravel(page)
  await page.reload()
  await expect(page.getByRole('dialog', { name: 'はじめての切符' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '切符に残す作業' })).toHaveValue('わたしの最初の切符')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '集めた切符を見る' })).toBeFocused()
  await page.keyboard.press('Escape')
  await page.mouse.move(1370, 860)
  await page.getByRole('button', { name: '使い方を見る' }).click()
  await receiveTicket(page)
  await expect(page.getByRole('textbox', { name: '切符に残す作業' })).toHaveValue('わたしの最初の切符')
  const replayed = await readTravel(page)
  expect(replayed.tickets).toEqual(received.tickets)
  expect(replayed.journey).toEqual(received.journey)
  await page.getByRole('button', { name: '手帳にしまう', exact: true }).click()
  await page.reload()
  await expect(page.locator('.opening-screen')).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect((await readTravel(page)).pendingArrivalId).toBeNull()
})

test('a running journey keeps its deadline and note when the guide grants a keepsake', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '窓辺へ', exact: true }).click()
  await page.getByRole('button', { name: 'スキップ' }).click()
  await page.getByRole('button', { name: '旅の手帳を開く' }).click()
  await page.getByRole('textbox', { name: '手帳のメモ' }).fill('本当の作業')
  await page.getByRole('button', { name: '乗車する', exact: true }).click()
  const before = await readTravel(page)
  await page.mouse.move(1370, 860)
  await page.getByRole('button', { name: '使い方を見る' }).click()
  await receiveTicket(page)
  await page.getByRole('button', { name: '手帳にしまう', exact: true }).click()
  expect((await readTravel(page)).journey).toEqual(before.journey)
  await expect(page.getByRole('textbox', { name: '手帳のメモ' })).toHaveValue('本当の作業')
  await page.getByRole('button', { name: '旅を終える', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '到着の切符' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '切符に残す作業' })).toHaveValue('本当の作業')
  const finished = await readTravel(page)
  expect(finished.tickets).toHaveLength(2)
  expect(finished.tickets[0].kind).toBeUndefined()
})

test('blocked storage still provides sample and welcome tickets for the current visit', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Unavailable', 'QuotaExceededError') } })
  await page.goto('/?demo=1')
  await page.getByRole('button', { name: '窓辺へ', exact: true }).click()
  await receiveTicket(page)
  await expect(page.getByRole('alert')).toContainText('切符を保存できません')
  await page.getByRole('button', { name: '手帳にしまう', exact: true }).click()
  await page.getByRole('button', { name: '集めた切符を見る' }).click()
  await page.getByRole('button', { name: '前の切符を見る' }).click()
  await expect(page.getByRole('textbox', { name: '切符に残す作業' })).toHaveValue('読みかけの本を、ひと章')
})
