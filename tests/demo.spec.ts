import { test, expect, type Page } from '@playwright/test'

test.beforeEach(async ({ page }) => { await page.emulateMedia({ reducedMotion: 'reduce' }) })

async function receiveTicket(page: Page) {
  await page.getByRole('button', { name: '次へ', exact: true }).click()
  await page.getByRole('button', { name: '次へ', exact: true }).click()
  await page.getByRole('button', { name: '切符を受け取る', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'はじめての切符' })).toBeVisible()
}

async function readTravel(page: Page, demo = false) {
  return page.evaluate(key => JSON.parse(localStorage.getItem(key)!), `syasou.travel.v2${demo ? '.demo' : ''}`)
}

test('the demo starts with three varied tickets, receives a keepsake, and retains sample edits without reseeding', async ({ page }) => {
  await page.goto('/?demo=1')
  await page.getByRole('button', { name: '窓辺へ', exact: true }).click()
  const initial = await readTravel(page, true)
  expect(initial.tickets).toHaveLength(3)
  expect(new Set(initial.tickets.map((ticket: { scene: string }) => ticket.scene)).size).toBe(3)
  expect(initial.tickets.every((ticket: { kind: string }) => ticket.kind === 'sample')).toBe(true)
  await receiveTicket(page)
  await page.getByRole('button', { name: '手帳にしまう', exact: true }).click()
  await expect(page.getByRole('button', { name: '集めた切符を見る' })).toBeFocused()
  await page.getByRole('button', { name: '集めた切符を見る' }).click()
  for (const title of ['読みかけの本を、ひと章', '企画のラフを描く', '明日のことを手帳に']) {
    await page.getByRole('button', { name: '前の切符を見る' }).click()
    await expect(page.getByRole('textbox', { name: '切符に残す作業' })).toHaveValue(title)
    await expect(page.locator('.ticket-on-top .ticket-stamp')).toHaveText('SAMPLE')
  }
  await expect(page.getByRole('button', { name: '前の切符を見る' })).toBeDisabled()
  await page.getByRole('textbox', { name: '切符に残す作業' }).fill('テストで書き直した切符')
  await page.getByRole('button', { name: '切符の裏を見る' }).click()
  await expect(page.getByRole('textbox', { name: '切符のメモ' })).toHaveValue(/自分のペース/)
  await page.getByRole('textbox', { name: '切符のメモ' }).fill('裏にも書き残せた。')
  await page.reload()
  await expect(page.locator('.opening-screen')).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const saved = await readTravel(page, true)
  expect(saved.tickets).toHaveLength(4)
  expect(saved.tickets.filter((ticket: { kind: string }) => ticket.kind === 'welcome')).toHaveLength(1)
  expect(saved.tickets[3].title).toBe('テストで書き直した切符')
  expect(saved.tickets[3].note).toBe('裏にも書き残せた。')
  expect(saved.journey.phase).toBe('idle')
  expect(await page.evaluate(() => localStorage.getItem('syasou.travel.v2'))).toBeNull()
})

